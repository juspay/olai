/**
 * THE SENTENCE a file delete has its reader read — one function, because the
 * sentence is the PR's whole argument and two spellings of it would be two
 * doors into one removal.
 *
 * `trash/question.ts`'s twin, one unit over: that one says RECORDS go and
 * counts them; this one says THE FILE goes and names it, because a file's
 * identity is its path in a way a row's never was. The two clauses keep the
 * same two jobs: the name (is this the right file — which is what a path IS,
 * and what the tree's basename-only rows never say), and the undo story,
 * said every time because a person may be told it at most once and still act
 * as though they knew.
 *
 * AND WHAT THE SENTENCE CANNOT SAY IS WHAT STILL NAMES IT. A non-empty
 * outline, a document a `doc` still points at: those are facts about the
 * SET, and a question drawn in a tab would be one reading behind the write.
 * So they are not the question's words — they are the PLANNER's refusal,
 * drawn on the page the person is standing on, in the same words an agent
 * meets: one gate, one sentence, whoever asked.
 */
export const deleteQuestion = (path: string): string =>
  `Delete ${path}? The file goes for good, and nothing puts it back: ` +
  `git's history is all that holds it.`
